/* USER CODE BEGIN 0 */
void change_speed(void){
	speed_gear=(speed_gear+1)%3;
	switch(speed_gear){
	case 0:target_speed=1.0f;
	break;
	case 1:target_speed=2.0f;
	break;
	case 2:target_speed=3.0f;
	break;
	}
}
float pid_calculate(float actual){
	float error=target_speed-actual;
	//积分项
    pid_integral+=error;
    if(pid_integral>pid_max_output){
    	pid_integral=pid_max_output;
    }else if(pid_integral<-pid_max_output){
    	pid_integral=-pid_max_output;
    }
    //微分项
    float derivative=error-last_error;
    float output=kp*error+ki*pid_integral+kd*derivative;
    last_error=error;
    return output;
}
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim){
	if(htim==&htim4){
		current_encoder=__HAL_TIM_GET_COUNTER(&htim3);
		encoder_different=current_encoder-last_encoder;
		current_speed=(float)encoder_different/1040/0.01f;
		last_encoder=current_encoder;
	}
}

